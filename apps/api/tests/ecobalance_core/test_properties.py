"""Property-based tests (PROMPT_CLAUDE_CODE.md §1 acceptance criteria):
linearity by scale, breakdown sums to 100%, allocation factor <= 1,
adding CCS never raises the footprint.
"""

from decimal import Decimal

from hypothesis import given
from hypothesis import strategies as st

from ecobalance_core.allocation import allocate
from ecobalance_core.engine import calculate
from ecobalance_core.models import (
    AllocationInput,
    CalculationInput,
    CoProductInput,
    ElectricityInput,
    ProcessEmissionsInput,
    RawMaterialInput,
)

_small_positive = st.decimals(
    min_value=Decimal("0.01"),
    max_value=Decimal("1000"),
    places=2,
    allow_nan=False,
    allow_infinity=False,
)


@given(
    quantity=_small_positive,
    scale=st.decimals(min_value=Decimal("1.1"), max_value=Decimal("5"), places=1),
)
def test_raw_material_emission_scales_linearly(quantity: Decimal, scale: Decimal) -> None:
    base = CalculationInput(
        product_id="ammonia",
        raw_materials=[
            RawMaterialInput(material_id="natural_gas_feedstock", quantity_t_per_unit=quantity)
        ],
    )
    scaled = CalculationInput(
        product_id="ammonia",
        raw_materials=[
            RawMaterialInput(
                material_id="natural_gas_feedstock", quantity_t_per_unit=quantity * scale
            )
        ],
    )
    base_result = calculate(base)
    scaled_result = calculate(scaled)
    assert scaled_result.scope3_kg_co2_per_unit == base_result.scope3_kg_co2_per_unit * scale


@given(
    raw_material_qty=_small_positive,
    electricity_mwh=st.decimals(min_value=Decimal("0"), max_value=Decimal("5"), places=2),
)
def test_breakdown_sums_to_roughly_100_percent(
    raw_material_qty: Decimal, electricity_mwh: Decimal
) -> None:
    calculation_input = CalculationInput(
        product_id="ammonia",
        raw_materials=[
            RawMaterialInput(
                material_id="natural_gas_feedstock", quantity_t_per_unit=raw_material_qty
            )
        ],
        electricity=(
            ElectricityInput(consumption_mwh_per_unit=electricity_mwh, region_id="oes_center")
            if electricity_mwh > 0
            else None
        ),
    )
    result = calculate(calculation_input)
    if result.pcf_full_kg_co2_per_unit == 0:
        assert result.breakdown == []
        return
    total_pct = sum((item.percentage for item in result.breakdown), start=Decimal("0"))
    assert abs(total_pct - Decimal("100")) < Decimal("1")


@given(
    main_mass=st.decimals(min_value=Decimal("1"), max_value=Decimal("1000"), places=1),
    co_mass=st.decimals(min_value=Decimal("0.1"), max_value=Decimal("1000"), places=1),
)
def test_mass_allocation_factor_is_bounded(main_mass: Decimal, co_mass: Decimal) -> None:
    calculation_input = CalculationInput(
        product_id="ammonia",
        actual_output_t=main_mass,
        co_products=[CoProductInput(name="by-product", quantity_t_per_year=co_mass)],
        allocation=AllocationInput(method="mass", rationale="generated by hypothesis"),
    )
    result = allocate(calculation_input)
    assert Decimal("0") <= result.factor <= Decimal("1")


@given(
    process_co2=st.decimals(min_value=Decimal("1"), max_value=Decimal("1000"), places=1),
    output=st.decimals(min_value=Decimal("1"), max_value=Decimal("100"), places=1),
    capture_fraction=st.decimals(min_value=Decimal("0"), max_value=Decimal("1"), places=2),
)
def test_capturing_more_co2_never_increases_footprint(
    process_co2: Decimal, output: Decimal, capture_fraction: Decimal
) -> None:
    captured = process_co2 * capture_fraction
    calculation_input = CalculationInput(
        product_id="ammonia",
        actual_output_t=output,
        process=ProcessEmissionsInput(
            co2_process_t_per_year=process_co2, captured_co2_t_per_year=captured
        ),
    )
    without_capture = calculation_input.model_copy(deep=True)
    without_capture.process.captured_co2_t_per_year = Decimal("0")  # type: ignore[union-attr]

    with_capture_result = calculate(calculation_input)
    without_capture_result = calculate(without_capture)

    assert (
        with_capture_result.pcf_full_kg_co2_per_unit
        <= without_capture_result.pcf_full_kg_co2_per_unit
    )
